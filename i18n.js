function rasApplyLang(lang) {
  const dict = I18N[lang] || I18N.ar;

  document.documentElement.setAttribute('lang', lang);
  document.documentElement.setAttribute('dir', lang === 'en' ? 'ltr' : 'rtl');

  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (dict[key] !== undefined) el.innerHTML = dict[key];
  });

  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (dict[key] !== undefined) el.setAttribute('placeholder', dict[key]);
  });

  document.querySelectorAll('.lang-switch button').forEach(btn => {
    btn.classList.toggle('active', btn.dataset.lang === lang);
  });

  try { localStorage.setItem('rasees_lang', lang); } catch (e) { /* ignore */ }
}

(function rasInitLang() {
  let saved = 'ar';
  try { saved = localStorage.getItem('rasees_lang') || 'ar'; } catch (e) { /* ignore */ }
  rasApplyLang(saved);

  document.querySelectorAll('.lang-switch button').forEach(btn => {
    btn.addEventListener('click', () => rasApplyLang(btn.dataset.lang));
  });
})();
